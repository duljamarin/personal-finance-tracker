/**
 * End-of-month forecast ("How will this month close?").
 *
 * Pure: no React, no Supabase, no clock. `today` is the user's LOCAL calendar
 * day as 'YYYY-MM-DD' (utils/date.toISODate) and is injected by the caller.
 * Inputs are decrypted rows; nothing here reads or stores anything.
 *
 * Calendar
 *   MONTH_START / MONTH_END   first / last day of TODAY's month
 *   DAYS_ELAPSED              day number of TODAY (includes today)
 *   DAYS_REMAINING            DAYS_IN_MONTH - DAYS_ELAPSED (tomorrow .. MONTH_END)
 *
 * Buckets (income and expense only; every amount lands in exactly one)
 *   ACTUAL        transactions dated MONTH_START .. TODAY
 *   SCHEDULED     (a) occurrences of active recurring rules this month that are
 *                     not a transaction yet (dedup key: rule id + date), including
 *                     ones already due but not posted yet
 *                 (b) transactions dated after TODAY within the month
 *   DISCRETIONARY ACTUAL expenses not generated by a recurring rule
 *
 * Everyday-spending pace
 *   CURRENT_RATE  = DISCRETIONARY / DAYS_ELAPSED
 *   HIST_RATE     = median over the history months of
 *                   (non-recurring expenses of the month / days of the month);
 *                   a history month is one of the LOOKBACK_MONTHS full months
 *                   before MONTH_START with at least one transaction.
 *                   CURRENT_RATE when there are none.
 *   WEIGHT        = DAYS_ELAPSED / DAYS_IN_MONTH
 *   BLENDED_RATE  = WEIGHT * CURRENT_RATE + (1 - WEIGHT) * HIST_RATE
 *   DISCRETIONARY_REMAINING = BLENDED_RATE * DAYS_REMAINING
 *   Income that is neither actual nor scheduled is never projected.
 *
 * Result
 *   PROJECTED_INCOME  = ACTUAL_INCOME + SCHEDULED_INCOME
 *   PROJECTED_EXPENSE = ACTUAL_EXPENSE + SCHEDULED_EXPENSE + DISCRETIONARY_REMAINING
 *   PROJECTED_NET     = PROJECTED_INCOME - PROJECTED_EXPENSE
 *   PESSIMISTIC / OPTIMISTIC_NET use max / min(CURRENT_RATE, HIST_RATE) for the
 *   remaining days instead of BLENDED_RATE.
 *
 * Per category (expenses; splits count toward their own categories; expenses
 * without a category share the UNCATEGORIZED bucket): ACTUAL and SCHEDULED
 * per category, and DISCRETIONARY_REMAINING shared out in proportion to each
 * category's own BLENDED_RATE(c), so the categories add up to the total.
 * PROJECTED_EXPENSE is summed from the category projections, which makes
 * "categories sum to the total" exact (it equals the formula above).
 */
import { baseAmountOf, median } from '../shared';
import { dateOnly, daysInMonthOf, monthOf, shiftMonth, ymd } from '../calendar';
import { occurrencesInRange } from '../recurringSchedule';

const COUNTED_TYPES = new Set(['income', 'expense']);

/** Category key for expenses without a category. */
export const UNCATEGORIZED = null;

const occurrenceKey = (ruleId, date) => `${ruleId}|${date}`;
const rateOf = (row) => (row.exchange_rate == null ? 1 : Number(row.exchange_rate) || 1);
const sum = (values) => values.reduce((total, v) => total + v, 0);
const amountOfRule = (rule) => (Number(rule.amount) || 0) * rateOf(rule);

/**
 * WEIGHT * current + (1 - WEIGHT) * history, written as
 * history + WEIGHT * (current - history) so equal rates blend to exactly that
 * rate, and kept between the two (the pessimistic / optimistic bounds).
 */
function blend(current, history, weight) {
  const mixed = history + weight * (current - history);
  return Math.min(Math.max(mixed, Math.min(current, history)), Math.max(current, history));
}

/** Expense amount per category: split parts when the row is split. */
function expenseParts(tx) {
  if (tx.has_splits && Array.isArray(tx.splits) && tx.splits.length > 0) {
    const rate = rateOf(tx);
    return tx.splits.map((s) => ({ categoryId: s.category_id ?? UNCATEGORIZED, amount: (Number(s.amount) || 0) * rate }));
  }
  return [{ categoryId: tx.category_id ?? UNCATEGORIZED, amount: baseAmountOf(tx) }];
}

export function computeForecast({ today, transactions = [], recurring = [], budgets = [], config }) {
  const { LOOKBACK_MONTHS, CONFIDENCE_FULL_MONTHS, EARLY_MONTH_DAYS } = config;

  // ── Calendar ────────────────────────────────────────────────────────────
  const TODAY = dateOnly(today);
  const month = monthOf(TODAY);
  const MONTH_START = month.start;
  const MONTH_END = month.end;
  const DAYS_IN_MONTH = month.daysInMonth;
  const DAYS_ELAPSED = month.day;
  const DAYS_REMAINING = DAYS_IN_MONTH - DAYS_ELAPSED;

  const txs = (transactions || []).filter((tx) => tx && COUNTED_TYPES.has(tx.type) && tx.date);

  // Per-category accumulators, in first-seen order (sums follow this order).
  const buckets = new Map();
  const bucket = (categoryId) => {
    if (!buckets.has(categoryId)) buckets.set(categoryId, { categoryId, actual: 0, scheduled: 0, discretionary: 0 });
    return buckets.get(categoryId);
  };

  // ── ACTUAL and SCHEDULED (b): this month's transactions ─────────────────
  const materialized = new Set();
  const scheduled = [];
  let ACTUAL_INCOME = 0;
  let SCHEDULED_INCOME = 0;

  for (const tx of txs) {
    const date = dateOnly(tx.date);
    if (tx.source_recurring_id) materialized.add(occurrenceKey(tx.source_recurring_id, date));
    if (date < MONTH_START || date > MONTH_END) continue;
    const isActual = date <= TODAY;

    if (tx.type === 'income') {
      const amount = baseAmountOf(tx);
      if (isActual) ACTUAL_INCOME += amount;
      else {
        SCHEDULED_INCOME += amount;
        scheduled.push({ date, type: tx.type, amount, title: tx.title, categoryId: tx.category_id ?? UNCATEGORIZED, source: 'entry', id: tx.id, due: false });
      }
      continue;
    }

    const parts = expenseParts(tx);
    for (const part of parts) {
      const b = bucket(part.categoryId);
      if (isActual) {
        b.actual += part.amount;
        if (!tx.source_recurring_id) b.discretionary += part.amount;
      } else {
        b.scheduled += part.amount;
      }
    }
    if (!isActual) {
      scheduled.push({ date, type: tx.type, amount: sum(parts.map((p) => p.amount)), title: tx.title, categoryId: tx.category_id ?? UNCATEGORIZED, source: 'entry', id: tx.id, due: false });
    }
  }

  // ── SCHEDULED (a): recurring occurrences not posted yet ─────────────────
  for (const rule of recurring || []) {
    if (!rule?.is_active || !COUNTED_TYPES.has(rule.type)) continue;
    const amount = amountOfRule(rule);
    for (const date of occurrencesInRange(rule, MONTH_START, MONTH_END).dates) {
      if (materialized.has(occurrenceKey(rule.id, date))) continue;
      if (rule.type === 'income') SCHEDULED_INCOME += amount;
      else bucket(rule.category_id ?? UNCATEGORIZED).scheduled += amount;
      scheduled.push({ date, type: rule.type, amount, title: rule.title, categoryId: rule.category_id ?? UNCATEGORIZED, source: 'recurring', id: rule.id, due: date <= TODAY });
    }
  }
  scheduled.sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0));

  // ── History months ──────────────────────────────────────────────────────
  const history = [];
  for (let back = 1; back <= LOOKBACK_MONTHS; back += 1) {
    const { y, m } = shiftMonth(month.y, month.m, -back);
    const days = daysInMonthOf(y, m);
    const start = ymd(y, m, 1);
    const end = ymd(y, m, days);
    let transactionCount = 0;
    let total = 0;
    const byCategory = new Map();
    for (const tx of txs) {
      const date = dateOnly(tx.date);
      if (date < start || date > end) continue;
      transactionCount += 1;
      if (tx.type !== 'expense' || tx.source_recurring_id) continue;
      for (const part of expenseParts(tx)) {
        total += part.amount;
        byCategory.set(part.categoryId, (byCategory.get(part.categoryId) || 0) + part.amount);
      }
    }
    if (transactionCount > 0) history.push({ days, total, byCategory });
  }

  // ── Pace ────────────────────────────────────────────────────────────────
  const DISCRETIONARY = sum([...buckets.values()].map((b) => b.discretionary));
  const CURRENT_RATE = DISCRETIONARY / DAYS_ELAPSED;
  const HISTORY_MONTHS = history.length;
  const HIST_RATE = HISTORY_MONTHS > 0 ? median(history.map((h) => h.total / h.days)) : CURRENT_RATE;
  const WEIGHT = DAYS_ELAPSED / DAYS_IN_MONTH;
  const BLENDED_RATE = blend(CURRENT_RATE, HIST_RATE, WEIGHT);
  const DISCRETIONARY_REMAINING = BLENDED_RATE * DAYS_REMAINING;

  // ── Per category ────────────────────────────────────────────────────────
  for (const h of history) for (const categoryId of h.byCategory.keys()) bucket(categoryId);
  const budgetByCategory = new Map();
  for (const b of budgets || []) {
    if (b?.category_id) budgetByCategory.set(b.category_id, Number(b.amount) || 0);
  }
  for (const categoryId of budgetByCategory.keys()) bucket(categoryId);

  const rows = [...buckets.values()].map((b) => {
    const currentRate = b.discretionary / DAYS_ELAPSED;
    const historyRates = history.map((h) => (h.byCategory.get(b.categoryId) || 0) / h.days);
    const histRate = HISTORY_MONTHS > 0 ? median(historyRates) : currentRate;
    const historyTotal = sum(history.map((h) => h.byCategory.get(b.categoryId) || 0));
    return { ...b, blendedRate: blend(currentRate, histRate, WEIGHT), historyTotal };
  });
  // Share of the remaining everyday spending: by BLENDED_RATE(c). When every
  // category's own median is 0 but the total pace is not (spending spread over
  // different categories each month), fall back to each category's share of
  // everyday spending seen so far (this month + history months).
  const blendedTotal = sum(rows.map((r) => r.blendedRate));
  const seenTotal = sum(rows.map((r) => r.discretionary + r.historyTotal));
  const shareOf = (r) => {
    if (blendedTotal > 0) return r.blendedRate / blendedTotal;
    if (seenTotal > 0) return (r.discretionary + r.historyTotal) / seenTotal;
    return 0;
  };

  const CATEGORIES = rows.map((r) => {
    const discretionaryRemaining = DISCRETIONARY_REMAINING * shareOf(r);
    const projected = r.actual + r.scheduled + discretionaryRemaining;
    const budget = budgetByCategory.has(r.categoryId) ? budgetByCategory.get(r.categoryId) : null;
    return {
      categoryId: r.categoryId,
      ACTUAL_EXPENSE: r.actual,
      SCHEDULED_EXPENSE: r.scheduled,
      BLENDED_RATE: r.blendedRate,
      DISCRETIONARY_REMAINING: discretionaryRemaining,
      PROJECTED_EXPENSE: projected,
      BUDGET: budget,
      PROJECTED_OVERSPEND: budget === null ? null : Math.max(0, projected - budget),
    };
  });

  // ── Result ──────────────────────────────────────────────────────────────
  const ACTUAL_EXPENSE = sum(CATEGORIES.map((c) => c.ACTUAL_EXPENSE));
  const SCHEDULED_EXPENSE = sum(CATEGORIES.map((c) => c.SCHEDULED_EXPENSE));
  const PROJECTED_EXPENSE = sum(CATEGORIES.map((c) => c.PROJECTED_EXPENSE));
  const PROJECTED_INCOME = ACTUAL_INCOME + SCHEDULED_INCOME;
  const PROJECTED_NET = PROJECTED_INCOME - PROJECTED_EXPENSE;
  // Same as INCOME - (ACTUAL + SCHEDULED + max|min rate * DAYS_REMAINING),
  // written relative to PROJECTED_EXPENSE so the three nets stay ordered.
  const PESSIMISTIC_NET = PROJECTED_INCOME - (PROJECTED_EXPENSE + (Math.max(CURRENT_RATE, HIST_RATE) - BLENDED_RATE) * DAYS_REMAINING);
  const OPTIMISTIC_NET = PROJECTED_INCOME - (PROJECTED_EXPENSE + (Math.min(CURRENT_RATE, HIST_RATE) - BLENDED_RATE) * DAYS_REMAINING);

  let CONFIDENCE = 'high';
  if (HISTORY_MONTHS === 0) CONFIDENCE = 'low';
  else if (HISTORY_MONTHS < CONFIDENCE_FULL_MONTHS) CONFIDENCE = 'medium';

  const BUDGETED_CATEGORIES = CATEGORIES
    .filter((c) => c.BUDGET !== null)
    .sort((a, b) => b.PROJECTED_OVERSPEND - a.PROJECTED_OVERSPEND || b.PROJECTED_EXPENSE - a.PROJECTED_EXPENSE);

  return {
    TODAY,
    MONTH_START,
    MONTH_END,
    DAYS_IN_MONTH,
    DAYS_ELAPSED,
    DAYS_REMAINING,
    ACTUAL_INCOME,
    ACTUAL_EXPENSE,
    SCHEDULED_INCOME,
    SCHEDULED_EXPENSE,
    SCHEDULED: scheduled,
    SCHEDULED_COUNT: scheduled.length,
    DISCRETIONARY,
    CURRENT_RATE,
    HISTORY_MONTHS,
    HIST_RATE,
    WEIGHT,
    BLENDED_RATE,
    DISCRETIONARY_REMAINING,
    PROJECTED_INCOME,
    PROJECTED_EXPENSE,
    PROJECTED_NET,
    PESSIMISTIC_NET,
    OPTIMISTIC_NET,
    CONFIDENCE,
    IS_EARLY_MONTH: DAYS_ELAPSED < EARLY_MONTH_DAYS,
    CATEGORIES,
    BUDGETED_CATEGORIES,
    BUDGETED_PROJECTED_EXPENSE: sum(BUDGETED_CATEGORIES.map((c) => c.PROJECTED_EXPENSE)),
  };
}
